// Isolated behavioral smoke test; never rewrites the live audio configuration.
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import {spawnSync} from 'node:child_process';
import {fileURLToPath} from 'node:url';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
fs.mkdirSync(path.join(root,'out'),{recursive:true});
const scratch=fs.mkdtempSync(path.join(root,'out','setup-test-'));
const film=path.join(scratch,'film');
for(const dir of ['scripts','src'])fs.mkdirSync(path.join(film,dir),{recursive:true});
fs.copyFileSync(path.join(root,'scripts/setup.mjs'),path.join(film,'scripts/setup.mjs'));
const source=[path.resolve(root,'../music/reference-bgm.m4a'),path.resolve(root,'../assets/music/reference-bgm.m4a')].find(p=>fs.existsSync(p));
assert(source,'Bundled source music missing');
const music=path.join(scratch,'assets/music');fs.mkdirSync(music,{recursive:true});
fs.copyFileSync(source,path.join(music,'reference-bgm.m4a'));
const call=(...args)=>spawnSync(process.execPath,[path.join(film,'scripts/setup.mjs'),...args],{cwd:film,encoding:'utf8'});
const config=path.join(film,'src/audio-config.json');
const first=call();assert.equal(first.status,0,first.stderr);assert.equal(JSON.parse(fs.readFileSync(config)).silent,false);
const saved=fs.readFileSync(config,'utf8');
assert.notEqual(call().status,0,'Setup must reject accidental replacement');
const short=call('--bgm',path.join(film,'public/audio/activation.wav'),'--force');
assert.notEqual(short.status,0,'A short BGM must fail');
assert.match(short.stderr,/needs at least/);
assert.equal(fs.readFileSync(config,'utf8'),saved,'A failed setup must keep the previous config');
assert.equal(call('--silent','--force').status,0);
assert.equal(JSON.parse(fs.readFileSync(config)).silent,true);
console.log(JSON.stringify({pass:true,checks:['initialized-project default path','real BGM track and duration','overwrite refusal','short BGM rejected','failed replacement preserves config','explicit silent option']},null,2));
